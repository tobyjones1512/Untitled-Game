// Compiles assembly/index.ts -> public/wasm/game.wasm and embeds the binary as
// base64 in src/lib/wasm/embedded.ts so the browser and Vercel functions can
// both instantiate it without touching the filesystem.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = resolve(root, "public/wasm/game.wasm");
mkdirSync(dirname(out), { recursive: true });

execFileSync(
  resolve(root, "node_modules/.bin/asc"),
  [
    "assembly/index.ts",
    "--outFile", out,
    "--runtime", "stub",
    "--optimizeLevel", "3",
    "--shrinkLevel", "2",
    "--noAssert",
    "--use", "abort=",
  ],
  { cwd: root, stdio: "inherit" },
);

const b64 = readFileSync(out).toString("base64");
writeFileSync(
  resolve(root, "src/lib/wasm/embedded.ts"),
  `// AUTO-GENERATED by scripts/build-wasm.mjs - do not edit.\nexport const GAME_WASM_BASE64 =\n  "${b64}";\n`,
);
console.log(`wasm built: ${readFileSync(out).length} bytes`);
